// scripts/build-lexicon.mjs
// Downloads the public O*NET skill vocabulary and writes the bundled fallback
// lexicon used when the Pro skill directory has not been updated yet.
// Usage: npm run build:lexicon

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
    ONET_SOFTWARE_CSV,
    ONET_ESSENTIAL_CSV,
    ONET_TRANSFERABLE_CSV,
    buildLexiconFromOnet,
    compactLexicon,
} from '../skill-lexicon.js';

const here = dirname(fileURLToPath(import.meta.url));
const outputPath = join(here, '..', 'libs', 'skills-lexicon.js');

async function download(url) {
    const response = await fetch(url, { headers: { 'user-agent': 'PocketResume build' } });
    if (!response.ok) throw new Error(`HTTP ${response.status} for ${url}`);
    return response.text();
}

const [softwareCsv, essentialCsv, transferableCsv] = await Promise.all([
    download(ONET_SOFTWARE_CSV),
    download(ONET_ESSENTIAL_CSV),
    download(ONET_TRANSFERABLE_CSV),
]);

const full = buildLexiconFromOnet({ softwareCsv, essentialCsv, transferableCsv });
const subset = {
    ...full,
    count: 0,
    terms: full.terms.filter((term) => {
        if (!/[A-Za-z]/.test(term.name)) return false;
        if (term.name.length < 2 || term.name.length > 48) return false;
        if (term.name.split(/\s+/).length > 5) return false;
        if (term.curated) return true;
        return term.hot || term.inDemand || term.category === 'technical' || term.aliases.length;
    }),
};
subset.count = subset.terms.length;

const compact = compactLexicon(subset);
const file = `// Generated by scripts/build-lexicon.mjs — O*NET 31.0 (CC BY 4.0, U.S. Department of Labor).
// Regenerate with: npm run build:lexicon
export const SKILL_LEXICON_BASE = ${JSON.stringify(compact)};
`;

await writeFile(outputPath, file, 'utf8');
const bytes = Buffer.byteLength(file, 'utf8');
console.log(`Wrote ${outputPath} — ${compact.terms.length} terms, ${(bytes / 1024).toFixed(1)} KB`);
